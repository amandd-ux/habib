object AppStringsProvider {
    private val enDays = listOf("Saturday", "Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday")
    private val faDays = listOf("شنبه", "یکشنبه", "دوشنبه", "سه‌شنبه", "چهارشنبه", "پنج‌شنبه", "جمعه")
    private val enMonths = listOf("Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec")
    private val faMonths = listOf("فروردین", "اردیبهشت", "خرداد", "تیر", "مرداد", "شهریور", "مهر", "آبان", "آذر", "دی", "بهمن", "اسفند")

    fun forLanguage(lang: AppLanguage): AppStrings = if (lang == AppLanguage.FA) persianStrings else englishStrings

    fun dayName(lang: AppLanguage, rawalDayIndex: Int): String =
        if (lang == AppLanguage.FA) faDays[rawalDayIndex.coerceIn(0, 6)] else enDays[rawalDayIndex.coerceIn(0, 6)]

    fun monthHeader(lang: AppLanguage, date: RawalDate): String {
        return if (lang == AppLanguage.FA) {
            val (jy, jm, _) = date.toJalali()
            "${faMonths[(jm - 1).coerceIn(0, 11)]} ${toLocalizedDigits(jy.toString(), lang)}"
        } else {
            "${enMonths[(date.month - 1).coerceIn(0, 11)]} ${date.year}"
        }
    }

    fun formatDate(lang: AppLanguage, isoDate: String): String {
        val d = RawalDate.parseIso(isoDate) ?: return isoDate
        return if (lang == AppLanguage.FA) {
            val (jy, jm, jd) = d.toJalali()
            toLocalizedDigits("$jy/${jm.toString().padStart(2, '0')}/${jd.toString().padStart(2, '0')}", lang)
        } else {
            "${enMonths[(d.month - 1).coerceIn(0, 11)]} ${d.day}, ${d.year}"
        }
    }

    fun formatShortDate(lang: AppLanguage, isoDate: String): String {
        val d = RawalDate.parseIso(isoDate) ?: return isoDate
        return if (lang == AppLanguage.FA) {
            val (_, jm, jd) = d.toJalali()
            toLocalizedDigits("$jm/$jd", lang)
        } else {
            "${d.month}/${d.day}"
        }
    }

    fun formatDayNumber(lang: AppLanguage, date: RawalDate): String {
        return if (lang == AppLanguage.FA) {
            val (_, _, jd) = date.toJalali()
            toLocalizedDigits(jd.toString(), lang)
        } else {
            date.day.toString()
        }
    }

    fun formatTime(lang: AppLanguage, hour: Int?, minute: Int?): String {
        if (hour == null || minute == null) return forLanguage(lang).notRecorded
        val raw = String.format(java.util.Locale.US, "%02d:%02d", hour, minute)
        return toLocalizedDigits(raw, lang)
    }

    fun formatDuration(lang: AppLanguage, totalMinutes: Int): String {
        val strings = forLanguage(lang)
        val safe = totalMinutes.coerceAtLeast(0)
        val h = safe / 60
        val m = safe % 60
        val text = when {
            h > 0 && m > 0 -> "$h${strings.hoursShort} $m${strings.minutesShort}"
            h > 0 -> "$h${strings.hoursShort}"
            else -> "$m${strings.minutesShort}"
        }
        return toLocalizedDigits(text, lang)
    }

    fun toLocalizedDigits(input: String, lang: AppLanguage): String {
        if (lang != AppLanguage.FA) return input
        val persianDigits = charArrayOf('۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹')
        val sb = StringBuilder(input.length)
        for (ch in input) {
            if (ch in '0'..'9') sb.append(persianDigits[ch - '0']) else sb.append(ch)
        }
        return sb.toString()
    }

